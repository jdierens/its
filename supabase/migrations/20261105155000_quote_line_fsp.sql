-- Forecasted sales price on a quote line.
-- DDS bid stays in our_unit_price. fsp_unit is the forecasted sell price.
-- fsp_ext follows our_ext: reply quantity, or the request quantity when the
-- reply quantity is null, times fsp_unit, rounded to cents.
-- No margin column. A dollar gap and a percent use different bases, and a buy
-- bid and a sell bid are not the same kind of price. The schema has no margin
-- column to copy.
-- A one-off backfill is not in this file.
-- Not applied here. Deploying does not run this file.

alter table public.quote_event_lines
  add column fsp_unit numeric(12, 2),
  add constraint quote_event_lines_fsp_nonnegative check (fsp_unit is null or fsp_unit >= 0);

alter table public.quote_event_lines
  add column fsp_ext numeric(12, 2) generated always as (
    case
      when coalesce(reply_qty, qty) is null or fsp_unit is null then null
      else round(coalesce(reply_qty, qty) * fsp_unit, 2)
    end
  ) stored;

comment on column public.quote_event_lines.fsp_unit is
  'Forecasted sales price per unit, in the event currency. Separate from our_unit_price, which is the DDS bid. Null until a forecast is entered.';

comment on column public.quote_event_lines.fsp_ext is
  'Reply quantity, or the request quantity when the reply quantity is null, times fsp_unit, rounded to cents. Null when either input is null. Generated by the database.';
